#!/usr/bin/env python3
"""Generate seeded random RV32 programs for the lockstep co-simulator."""

import argparse
import hashlib
import json
import random
import sys
from collections import Counter

from instructions import ALL_GENERATORS, BASIC_GENERATORS
from instructions.common import DATA_BYTES, SAFE_REGS, initial_register_value

PROFILES = ("mixed", "memory", "dependencies", "control", "float")
CLASS_WEIGHTS = {
    "mixed": {},
    "memory": {"mem": 8},
    "dependencies": {"arith": 8},
    "control": {"branch": 6, "ctrl": 6},
    "float": {"float": 8},
}


def parse_extensions(isa: str) -> set:
    """Extract single- and multi-letter extensions from an RV32 ISA string."""

    body = isa.lower()
    if body.startswith("rv32"):
        body = body[4:]

    head, *multi_letter_extensions = body.split("_")
    extensions = set(head)
    extensions.update(ext for ext in multi_letter_extensions if ext)
    return extensions


# Kept for callers that imported the old helper directly.
parse_ext = parse_extensions


def combined_seed(seed: int, generation_seed: int) -> int:
    """Deterministically identify one test within one generator campaign."""

    # Campaign zero uses the seed directly. Other campaigns use a stable mix;
    # reproducing source also requires the same generator revision and options.
    if generation_seed == 0:
        return seed
    material = f"rvgen-v1:{generation_seed}:{seed}".encode("ascii")
    return int.from_bytes(hashlib.sha256(material).digest(), "big")


def build_pool(classes: set, extensions: set):
    """Return generators compatible with the requested classes and ISA."""

    return [
        generator
        for generator in ALL_GENERATORS
        if generator.is_enabled(classes, extensions)
    ]


def count_instruction(line: str, counts: Counter) -> None:
    stripped = line.strip()
    mnemonic = stripped.split()[0] if stripped else ""
    if mnemonic and not mnemonic.endswith(":") and not mnemonic.startswith((".", "#")):
        counts[mnemonic] += 1


def emit_assembly_block(raw_block: str, counts: Counter):
    """Convert a multiline assembly block to GCC inline-assembly strings."""

    emitted = []
    for line in raw_block.splitlines():
        line = line.strip()
        if line:
            count_instruction(line, counts)
            emitted.append(f'        "{line}\\n"')
    return emitted


def generate_instruction_stream(rng, instruction_count, pool, counts, profile="mixed", scenarios=None):
    emitted = []
    scenarios = scenarios if scenarios is not None else Counter()
    weights = [CLASS_WEIGHTS[profile].get(spec.instruction_class, 1)
               * (3 if spec in BASIC_GENERATORS else 1) for spec in pool]
    # Visit every enabled family once before weighted random selection. Long
    # streams then alternate broad operands with small dependency-heavy windows.
    warmup = list(pool)
    rng.shuffle(warmup)
    for block_id in range(instruction_count):
        if block_id % 32 == 0:
            hot = profile == "dependencies" or rng.random() < 0.65
            rng.register_pool = tuple(rng.sample(SAFE_REGS, rng.randint(3, 8))) if hot else SAFE_REGS
        generator = warmup[block_id] if block_id < len(warmup) else rng.choices(pool, weights)[0]
        scenarios[generator.generate.__name__.removeprefix("generate_")] += 1
        emitted.append(f'        "rvgen_block_{block_id}:\\n"')
        emitted.extend(emit_assembly_block(generator.generate(rng, block_id), counts))
    return "\n".join(emitted)


def generate_register_initialization(rng, counts):
    emitted = []
    for register in SAFE_REGS:
        line = f"li {register}, {initial_register_value(rng)}"
        count_instruction(line, counts)
        emitted.append(f'        "{line}\\n"')

    # x30 is only consumed after a loop generator has initialized it.  Giving
    # it a known startup value still makes the generated program self-contained.
    line = "li x30, 0"
    count_instruction(line, counts)
    emitted.append(f'        "{line}\\n"')
    return "\n".join(emitted)


def render_program(args, register_initialization, instruction_stream):
    # Nonzero memory makes stale refills, lane swaps, and missing stores visible
    # even when a location has never previously been written by the CPU.
    data_rng = random.Random(f"data:{args.gen_seed}:{args.seed}")
    data = [data_rng.randrange(256) for _ in range(DATA_BYTES)]
    initializer = ",\n".join("    " + ",".join(str(v) for v in data[i:i+32])
                             for i in range(0, DATA_BYTES, 32))
    return f"""// AUTO-GENERATED by rvgen.py
// gen_seed={args.gen_seed} seed={args.seed} ext={args.ext} priv={args.priv}
// profile={args.profile}; blocks={args.n}; data/cache/line={DATA_BYTES}/{args.cache_bytes}/{args.line_bytes}

// Data area reserved for load/store operations (aligned).
static volatile unsigned char data_area[{DATA_BYTES}]
    asm("data_area") __attribute__((aligned(64))) = {{
{initializer}
}};

void main(void)
{{
    register unsigned long base asm("x31") =
        (unsigned long)data_area;

    asm volatile (

        // --- Initialize source registers
        //     (known, deterministic values) ---

{register_initialization}

        // --- Random instruction stream ---

        ".option push\\n"
        ".option norvc\\n"
        "rvgen_begin:\\n"
{instruction_stream}
        "rvgen_end:\\n"
        ".option pop\\n"

        :
        : "r"(base)
        : "x5","x6","x7","x8","x9","x10",
          "x11","x12","x13","x14","x15",
          "x16","x17","x18","x19","x20",
          "x21","x22","x23","x24","x25",
          "x26","x27","x28","x29","x30",
          "memory"
    );
}}
"""


def write_coverage(path, counts):
    if not path:
        return
    coverage_file = sys.stdout if path == "-" else open(path, "w", encoding="utf-8")
    try:
        for mnemonic, count in sorted(counts.items()):
            coverage_file.write(f"{mnemonic} {count}\n")
    finally:
        if coverage_file is not sys.stdout:
            coverage_file.close()


def parse_args(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument(
        "--gen-seed",
        type=int,
        default=0,
        help="generator campaign seed; combines with --seed for reproducible variation",
    )
    parser.add_argument("--n", type=int, default=2000, help="number of generator blocks")
    parser.add_argument("--profile", choices=("auto", *PROFILES), default="auto")
    parser.add_argument("--cache-bytes", type=int, default=4096)
    parser.add_argument("--line-bytes", type=int, default=16)
    parser.add_argument("--manifest", help="write reproducibility metadata and static scenario counts as JSON")
    parser.add_argument(
        "--class",
        dest="classes",
        default="arith,mem,branch,ctrl",
        help="classes: arith,mem,branch,ctrl,float,fence (csv)",
    )
    parser.add_argument(
        "--ext",
        default="rv32im_zfinx_zba_zbs_zicsr",
        help="ISA string (= $(ISA) from config.mk)",
    )
    parser.add_argument(
        "--no-fdiv",
        action="store_true",
        help="compatibility option; fdiv/fsqrt generation is always disabled",
    )
    parser.add_argument("--priv", default="mu")
    parser.add_argument("--out", default="cosim/tests/prog.c")
    parser.add_argument(
        "--cov-out",
        dest="cov_out",
        default="",
        help="write a per-mnemonic histogram for this invocation",
    )
    parser.add_argument(
        "--quiet",
        action="store_true",
        help="suppress the generation summary (useful when coverage is sent to stdout)",
    )
    args = parser.parse_args(argv)
    if args.n < 1:
        parser.error("--n must be positive")
    if (args.line_bytes < 16 or args.line_bytes & (args.line_bytes - 1)
            or args.cache_bytes < args.line_bytes or args.cache_bytes & (args.cache_bytes - 1)
            or args.cache_bytes > DATA_BYTES // 2):
        parser.error("cache/line sizes must be powers of two, 16 <= line <= cache <= data/2")
    known_classes = {name for spec in ALL_GENERATORS for name in (spec.instruction_class, *spec.aliases)}
    unknown = {name.strip() for name in args.classes.split(",") if name.strip()} - known_classes
    if unknown:
        parser.error(f"unknown classes: {sorted(unknown)}")
    return args


def main(argv=None):
    args = parse_args(argv)
    rng = random.Random(combined_seed(args.seed, args.gen_seed))
    if args.profile == "auto":
        args.profile = rng.choice(PROFILES)
    rng.cache_bytes = args.cache_bytes
    rng.line_bytes = args.line_bytes
    classes = {name.strip() for name in args.classes.split(",") if name.strip()}
    extensions = parse_extensions(args.ext)
    pool = build_pool(classes, extensions)

    if not pool:
        print(
            "rvgen: no active instruction family for the selected classes/extensions",
            file=sys.stderr,
        )
        return 1

    counts = Counter()
    scenarios = Counter()
    instruction_stream = generate_instruction_stream(rng, args.n, pool, counts, args.profile, scenarios)
    register_initialization = generate_register_initialization(rng, counts)
    program = render_program(args, register_initialization, instruction_stream)

    with open(args.out, "w", encoding="utf-8") as output_file:
        output_file.write(program)
    write_coverage(args.cov_out, counts)
    if args.manifest:
        metadata = {"schema": 1, "seed": args.seed, "gen_seed": args.gen_seed,
                    "profile": args.profile, "isa": args.ext, "classes": sorted(classes),
                    "blocks": args.n, "cache_bytes": args.cache_bytes, "line_bytes": args.line_bytes,
                    "source_sha256": hashlib.sha256(program.encode()).hexdigest(),
                    "scenarios": dict(sorted(scenarios.items())), "static_opcodes": dict(sorted(counts.items()))}
        with open(args.manifest, "w", encoding="utf-8") as output_file:
            json.dump(metadata, output_file, indent=2, sort_keys=True)
            output_file.write("\n")

    if not args.quiet:
        print(
            f"rvgen: wrote {args.out} "
            f"({args.n} generator blocks, "
            f"gen_seed={args.gen_seed}, seed={args.seed}, "
            f"classes={sorted(classes)}, "
            f"active extensions={sorted(extensions)})"
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
